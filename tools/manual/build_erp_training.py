_missing = []
_placed = []


def fig(d, filename, caption, width_cm=None):
    """캡처가 있으면 넣고, 없으면 자리 표시만 남긴다.

    메일 주소를 가린 «_masked» 사본이 있으면 그것을 먼저 쓴다(mask_emails.py).
    """
    stem, ext = os.path.splitext(filename)
    for cand in (f"{stem}_masked{ext}", filename):
        path = os.path.join(CAP, cand)
        if os.path.exists(path):
            if width_cm is None:
                d.figure(path, caption)
            else:
                d.figure(path, caption, width_cm=width_cm)
            _placed.append(os.path.basename(path))
            return
    _missing.append(filename)
    d.note("화면 캡처 예정", f"{caption}  ({filename})", warn=True)


def fig_wide(d, filename, caption, width_cm=15.5):
    """높이 상한을 넘겨 «크게» 넣는 그림.

    ⚠ 서식 틀(manual_kit)의 그림 규칙을 일부러 비켜 간다. 그쪽은 높이를 5.9cm 로
      묶어 빈 쪽을 막는데, 화면 «전체» 를 담은 캡처는 그 크기로는 글씨를 읽을 수
      없다. 교육 자료에서 포털 첫 화면은 이야기의 출발점이라 읽히지 않으면 쓸모가
      없으므로, 이 그림에만 예외를 둔다.
    ⚠ 쓰는 자리를 «장 첫머리» 로 한정한다. 본문 한가운데에 큰 그림을 넣으면
      앞 쪽에 빈 공간이 남는다 — 서식 틀이 경고하는 바로 그 증상이다.
    """
    path = os.path.join(CAP, filename)
    if not os.path.exists(path):
        _missing.append(filename)
        d.note("화면 캡처 예정", f"{caption}  ({filename})", warn=True)
        return
    p = d.doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.line_spacing = 1.0
    p.paragraph_format.space_after = Pt(2)
    p.paragraph_format.keep_with_next = True   # 그림과 설명이 갈라지지 않게
    p.add_run().add_picture(path, width=Cm(width_cm))
    cap = d.doc.add_paragraph()
    cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
    cap.paragraph_format.line_spacing = 1.0
    cap.paragraph_format.space_after = Pt(7)
    _apply_font(cap.add_run(caption), size=9, color=CAPTION)
    _placed.append(filename)


