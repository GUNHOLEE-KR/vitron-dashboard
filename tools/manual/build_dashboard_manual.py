def fig(d, filename, caption, width_cm=None):
    """캡처가 있으면 넣고, 없으면 자리 표시만 남긴다.

    메일 주소를 가린 «_masked» 사본이 있으면 그것을 먼저 쓴다
    (mask_emails.py 가 만든다). 매뉴얼에 개인 메일이 실리지 않게 하기 위함이다.

    ⚠ 폭을 여기서 정하지 않는다. manual_kit 이 원본 픽셀을 보고 «폭·높이 상한·확대
      배율» 을 함께 만족시키는 값을 계산한다. 예전에는 모든 그림에 15.5cm 를 일률로
      줘서, 큰 캡처는 반 쪽을 차지하고 128px 짜리 조각은 4.6배로 늘어나 뭉개졌다.
      특별히 작게/크게 넣어야 할 그림만 width_cm 을 준다.
    """
    stem, ext = os.path.splitext(filename)
    for cand in (f"{stem}_masked{ext}", filename):
        path = os.path.join(CAP, cand)
        if os.path.exists(path):
            if width_cm is None:
                d.figure(path, caption)
            else:
                d.figure(path, caption, width_cm=width_cm)
            _placed.append(os.path.basename(path))
            return
    _missing.append(filename)
    d.note("화면 캡처 예정", f"{caption}  ({filename})", warn=True)


