def group_row(ws, r, text):
    ws.cell(row=r, column=1, value=text)
    ws.merge_cells(start_row=r, start_column=1, end_row=r, end_column=NCOL)
    c = ws.cell(row=r, column=1)
    c.font = Font(name=FONT, size=10, bold=True, color="FFFFFF")
    c.fill = GRP_FILL
    c.alignment = Alignment(horizontal="left", vertical="center")
    c.border = BOX
    ws.row_dimensions[r].height = 20


def put(ws, r, vals, band=False, fill=None, color=None):
    for i, v in enumerate(vals, start=1):
        c = ws.cell(row=r, column=i, value=v)
        c.font = Font(name=FONT, size=10)
        c.alignment = CEN if i in CENTER else LEFT
        c.border = BOX
        if fill is not None:
            c.fill = fill
        elif band:
            c.fill = BAND_FILL
    if color:
        ws.cell(row=r, column=5).font = Font(name=FONT, size=10, bold=True, color=color)


def sheet_tc(wb):
    ws = wb.create_sheet("TC 목록")
    for i, (h, w) in enumerate(zip(HEADERS, WIDTHS), start=1):
        c = ws.cell(row=1, column=i, value=h)
        c.font = Font(name=FONT, size=10, bold=True, color="FFFFFF")
        c.fill = HEAD_FILL
        c.alignment = CEN
        c.border = BOX
        ws.column_dimensions[get_column_letter(i)].width = w
    ws.row_dimensions[1].height = 26
    ws.freeze_panes = "C2"

    r = 2
    group_row(ws, r, "■ 실환경 검증 — 실 서버·실 설비·실 PC 로 사람이 수행한다.")
    r += 1
    for n, (mod, ask, how, fix, note) in enumerate(FIELD, start=1):
        put(ws, r, [f"TC-D-{n:02d}", mod, ask, how, "적합", VERIFIER, "", fix, note],
            band=(n % 2 == 0), color=GREEN)
        r += 1

    group_row(ws, r, "■ 미수행 — 자원·현장 조건이 갖춰져야 할 수 있다. "
                     "함께 실어 「전부 확인했다」로 읽히지 않게 한다.")
    r += 1
