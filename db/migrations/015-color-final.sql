-- 015. 색 확정 — 세 번 틀리고 «네 번째에 재서» 정했다 (2026-08-25)
-- ============================================================
-- 012·013·014 를 대체한다. 실패의 기록을 남겨 둔다 — 같은 실수를 반복하지 않기 위해서다.
--
--   1차(012·013) 색상(hue)만 40도씩 벌리고 «명도·채도는 전부 같은 단계» 로 뒀다
--                → 「다 비슷하다」
--   2차          ΔE(색 차이)를 재 봤더니 모든 쌍이 30 이상인데도 여전히 비슷했다.
--                지적받은 쌍이 전부 «같은 색 이름» 이었다 —
--                파랑–보라 / 빨강–주황–분홍 / 초록–연두
--                → 사람은 작은 점을 «미세한 거리» 가 아니라 «색 이름» 으로 분류한다
--   3차(014)     이름을 전부 다르게 하고 ΔE 49 까지 올렸는데도
--                남색(밝기 27) 과 적갈(밝기 28) 이 「너무 비슷하다」 고 했다.
--                🔑 **둘 다 아주 어두우면 12px 점에서는 색상이 안 보이고
--                   그냥 «검은 점» 둘로 보인다.** ΔE 는 큰 면적 기준이라
--                   작은 점에 그대로 쓸 수 없다.
--   4차(이 파일)  세 조건을 함께 걸고 «컴퓨터가» 골랐다 —
--                ①밝기 45~85 로 후보를 자른다 (어두운 색은 아예 안 쓴다)
--                ②색 이름이 서로 겹치지 않을 것
--                ③그 안에서 가장 가까운 쌍의 ΔE 를 최대로
--                결과 = 직원 ΔE **52.9** · 차량 **96.9** (1차는 34.4였다)
--
--   🔑 고광용은 일정을 넣지 않으므로 «팔레트에서 아예 뺐다» (사용자 지시).
--      회색 한 자리를 비워 주는 대신 실제로 쓰는 7명이 7색을 나눠 갖는다.
--
--   고르는 도구 = `tools/pick-colors.mjs` — 버리지 말 것. 사람이 늘면 다시 돌린다.
--
-- ⚠ admin 계정으로 실행할 것

-- ── 직원 ──────────────────────────────────────────────
UPDATE workers SET color = c.hex
  FROM (VALUES
    ('이건호', '#2563eb'),   -- 파랑     밝기 46   ← 「파랑으로」 사용자 지정
    ('윤기곤', '#ea580c'),   -- 주황     밝기 57   ← 파랑의 보색. 가장 멀리 떼어 놨다
    ('김동현', '#ec4899'),   -- 분홍     밝기 57
    ('이상기', '#06b6d4'),   -- 청록     밝기 68
    ('김정열', '#4ade80'),   -- 연초록   밝기 79
    ('윤인철', '#d8b4fe'),   -- 연보라   밝기 79
    ('송지형', '#facc15'),   -- 노랑     밝기 84
    ('고광용', '#94a3b8')    -- 회색  — 팔레트 밖. 일정을 넣지 않는다
  ) AS c(nm, hex)
 WHERE workers.name = c.nm;

-- ── 차량 ── 위 7색과도 ΔE 25 이상 떨어뜨렸다.
--    주 뷰의 차량 기준에서는 행(차량)과 배지(사람)가 «동시에» 보이기 때문이다.
UPDATE schedule_vehicles SET color = c.hex
  FROM (VALUES
    ('24구 7598',  '#ef4444'),   -- 빨강       밝기 55
    ('3422',       '#0e7490'),   -- 짙은 청록  밝기 45
    ('15도 3955',  '#84cc16'),   -- 라임       밝기 75
    ('129누 9183', '#d946ef')    -- 자주       밝기 57
  ) AS c(pl, hex)
 WHERE schedule_vehicles.plate = c.pl;
