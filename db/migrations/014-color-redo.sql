-- 014. 색을 다시 고른다 — 이번에는 «재서» 고른다 (2026-08-25)
-- ============================================================
-- 🔴 012·013 에서 고른 색이 「다 비슷하다」 는 지적을 받았다. 두 번 틀렸다.
--
--   1차 실패 — 색상(hue)만 40도씩 벌리고 «명도·채도는 전부 같은 단계» 로 뒀다.
--              12px 점에서는 그게 그냥 「같은 계열」 로 보인다.
--   2차 실패 — ΔE(색 차이)를 재 봤더니 모든 쌍이 30 이상이었는데도 여전히 비슷했다.
--              지적받은 쌍이 전부 «같은 색 이름» 이었다 —
--              파랑–보라 / 빨강–주황–분홍 / 초록–연두.
--
--   🔑 배운 것 = 사람은 작은 점을 «미세한 거리» 가 아니라 «색 이름» 으로 분류한다.
--      그래서 두 조건을 함께 걸고 «컴퓨터가» 고르게 했다.
--        ① 모든 쌍의 ΔE 를 최대로 (직원 49.4 · 차량 89.7 — 전에는 34.4)
--        ② 색 이름이 서로 겹치지 않을 것
--        ③ 차량 색은 직원 색과도 25 이상 떨어질 것
--           (주 뷰 차량 기준에서 행=차량, 배지=사람이 «동시에» 보인다)
--      고르는 도구는 `tools/pick-colors.mjs` 에 남겨 둔다.
--
-- ⚠ admin 계정으로 실행할 것

-- ── 직원 ──────────────────────────────────────────────
-- 밝기가 27~84 로 넓게 퍼져 있다. 색상만이 아니라 명도로도 갈린다.
UPDATE workers SET color = c.hex
  FROM (VALUES
    ('이건호', '#1e3a8a'),   -- 남색   (밝기 27)  ← 「파랑으로」 사용자 지정
    ('윤기곤', '#7f1d1d'),   -- 적갈   (밝기 28)
    ('윤인철', '#9333ea'),   -- 보라   (밝기 45)
    ('이상기', '#ea580c'),   -- 주황   (밝기 57)
    ('김동현', '#f472b6'),   -- 분홍   (밝기 65)
    ('김정열', '#22c55e'),   -- 초록   (밝기 70)
    ('송지형', '#facc15'),   -- 노랑   (밝기 84)
    ('고광용', '#94a3b8')    -- 회색   — 일정을 넣지 않으므로 좋은 색을 쓰지 않는다
  ) AS c(nm, hex)
 WHERE workers.name = c.nm;

-- ── 차량 ──────────────────────────────────────────────
UPDATE schedule_vehicles SET color = c.hex
  FROM (VALUES
    ('24구 7598',  '#b91c1c'),   -- 진빨강
    ('3422',       '#0891b2'),   -- 청록
    ('15도 3955',  '#65a30d'),   -- 올리브초록
    ('129누 9183', '#a21caf')    -- 자주
  ) AS c(pl, hex)
 WHERE schedule_vehicles.plate = c.pl;
