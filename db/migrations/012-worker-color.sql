-- 012. 직원마다 «자기 색» 을 박아 둔다 (2026-08-25)
-- ============================================================
-- 🔴 원인 = 팔레트가 8색인데 직원이 10명이라 색이 «한 바퀴 돌아» 겹쳤다.
--    자동 배정은 `COLORS[순번 % 8]` 이었고 순번은 입사일 순이라
--      고광용(0) ↔ 송지형(8)   — 정확히 같은 파랑
--      이건호(1) ↔ 김동현(9)   — 정확히 같은 초록
--    이 둘이 «완전히 같은 색» 이었다. 게다가 퇴사자 2명이 순번을 차지해
--    사람을 넣고 뺄 때마다 남의 색까지 밀렸다.
--
-- 🔑 그래서 «계산» 이 아니라 «값» 으로 둔다. 사람이 늘거나 빠져도 남의 색이 안 바뀐다.
--    비워 두면 예전처럼 팔레트에서 자동으로 고른다(새로 들어온 사람).
--
-- 색은 색상환에서 고르게 벌렸다 — 옆자리끼리 최소 40도 이상 떨어뜨렸다.
--   빨강 0° · 주황 32° · 연두 82° · 초록 162° · 파랑 220° · 보라 262° · 분홍 333°
-- 고광용(대표이사)은 일정을 넣지 않으므로 «좋은 색을 쓰지 않고» 회색으로 둔다
-- (2026-08-25 사용자 지시). 그만큼 다른 사람이 뚜렷한 색을 하나씩 더 가져간다.
--
-- ⚠ admin 계정으로 실행할 것

ALTER TABLE workers ADD COLUMN IF NOT EXISTS color VARCHAR(7);

COMMENT ON COLUMN workers.color IS
  '달력·차트에서 이 사람을 나타내는 색(#rrggbb). 비우면 팔레트에서 자동 배정.';

UPDATE workers SET color = c.hex
  FROM (VALUES
    ('윤기곤', '#dc2626'),   -- 빨강
    ('이상기', '#d97706'),   -- 주황
    ('송지형', '#65a30d'),   -- 연두
    ('김정열', '#059669'),   -- 초록
    ('이건호', '#2563eb'),   -- 파랑  (사용자 지정)
    ('윤인철', '#7c3aed'),   -- 보라
    ('김동현', '#db2777'),   -- 분홍
    ('고광용', '#94a3b8')    -- 회색  (일정을 넣지 않는다)
  ) AS c(nm, hex)
 WHERE workers.name = c.nm;
