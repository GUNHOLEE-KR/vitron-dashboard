-- 016. 색 확정 — 네 번 틀리고 «규칙을 코드에 넣어» 정했다 (2026-08-25)
-- ============================================================
-- 012~015 를 대체한다. 실패를 다 적어 둔다 — 다음 사람이 같은 길을 안 가도록.
--
--   1차 색상(hue)만 40도씩 벌리고 «명도·채도는 전부 같은 단계» → 「다 비슷하다」
--   2차 ΔE 가 모든 쌍 30 이상인데도 비슷했다. 지적받은 쌍이 전부 «같은 색 이름» —
--       파랑–보라 / 빨강–주황–분홍 / 초록–연두
--   3차 이름을 다르게 하고 ΔE 49 까지 올렸는데 남색(밝기27)·적갈(밝기28) 이 붙어 보였다
--       → **둘 다 어두우면 색상이 안 보이고 «검은 점» 둘이 된다**
--   4차 밝기를 45 이상으로 올렸더니 주황(밝기57)·분홍(밝기57) 이 붙어 보였다
--       → **색상이 가까운데 밝기까지 같으면 붙는다.** ΔE 73.9 여도 그렇다.
--
--   🔑 5차 = 「색상 간격」 과 「밝기 간격」 을 «함께» 보는 규칙을 코드에 박고
--            되짚어 찾기로 «규칙을 지키는 조합 9,684개» 를 전부 훑어 최선을 골랐다.
--              색상이 멀면(≥55도)        밝기는 상관없다
--              색상이 어중간하면(35~55도) 밝기를 16 이상 벌린다
--              색상이 가까우면(<35도)     밝기를 26 이상 벌린다
--            결과 = 직원 ΔE **60.6** · 차량 **82.1** (1차는 34.4 였다)
--
--   ⚠ ΔE 는 «큰 면적» 기준이라 12px 점에는 그대로 쓸 수 없다. 보조 지표로만 본다.
--   ⚠ 탐욕으로는 못 찾는다 — 「지금 가장 먼 색」 을 집으면 뒤에서 막다른 길에 빠진다.
--
--   고르는 도구 = `tools/pick-colors.mjs` — 버리지 말 것. 사람이 늘면 다시 돌린다.
--
-- ⚠ admin 계정으로 실행할 것

-- ── 직원 ── 색상 0·48·142·187·217·293·327 / 밝기 48~86
UPDATE workers SET color = c.hex
  FROM (VALUES
    ('윤기곤', '#dc2626'),   -- 빨강       색상   0  밝기 48
    ('송지형', '#facc15'),   -- 노랑       색상  48  밝기 84
    ('김정열', '#16a34a'),   -- 초록       색상 142  밝기 59
    ('이상기', '#67e8f9'),   -- 밝은 하늘  색상 187  밝기 86
    ('이건호', '#3b82f6'),   -- 파랑       색상 217  밝기 56  ← 사용자 지정
    ('윤인철', '#c026d3'),   -- 자주       색상 293  밝기 49
    ('김동현', '#f9a8d4'),   -- 연분홍     색상 327  밝기 78
    -- ⚠ 회색은 «완전 무채색» 이어야 한다. 처음에 쓴 `#94a3b8` 은 이름만 회색이고
    --   실제로는 색상 215 의 «푸른 회색» 이라 이건호의 파랑(색상 217)과 2도 차이였다.
    --   채도가 낮아 ΔE 는 56 이지만 작은 점에서는 「연한 파랑」 과 「파랑」 으로 보인다.
    --   `#a3a3a3` 은 R=G=B 라 색상이 아예 없어 어떤 유채색과도 채도로 갈린다.
    ('고광용', '#a3a3a3')    -- 무채색 회색 — 팔레트 밖. 일정을 넣지 않는다
  ) AS c(nm, hex)
 WHERE workers.name = c.nm;

-- ── 차량 ──
-- ⚠ 직원과 «같은 규칙» 으로 갈라놓으려 했더니 후보가 2개로 줄어 답이 없었다 —
--   7색이 색상환을 이미 다 채웠기 때문이다.
--   🔑 차량 행(왼쪽 라벨)과 사람 배지(칸 안)는 «자리가 달라» 나란히 놓고 견주지 않는다.
--      그래서 차량끼리만 확실히 가르고, 직원 색과는 ΔE 30 만 띄웠다(실제 32.4).
UPDATE schedule_vehicles SET color = c.hex
  FROM (VALUES
    ('24구 7598',  '#f97316'),   -- 주황   색상  25  밝기 64
    ('3422',       '#a3e635'),   -- 라임   색상  83  밝기 84
    ('15도 3955',  '#0d9488'),   -- 청록   색상 175  밝기 55
    ('129누 9183', '#c084fc')    -- 연보라 색상 270  밝기 66
  ) AS c(pl, hex)
 WHERE schedule_vehicles.plate = c.pl;
